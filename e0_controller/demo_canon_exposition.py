# ──────────────────────────────────────────────
# Navigation Trace Generator
# ──────────────────────────────────────────────

def generate_trace() -> str:
    """Navigate the canon and produce a human-readable trace."""
    cl = load_canon("ontodynamics")
    ctrl = E0Controller(cl.landscape, lambda s, t: Outcome.SUCCESS)

    lines = []
    current = "differenz"
    goal = "negative_notwendigkeit"

    for step in range(20):
        r = ctrl.cycle(current)
        if r is None:
            lines.append(f"Step {step+1}: STUCK at {current}")
            break

        n_cands = len(r.candidates)
        lines.append(
            f"Step {step+1}: {r.source} -> {r.target}"
            f"  (s_eff={r.s_eff:.4f}, candidates={n_cands})"
        )
        current = r.target
        if current == goal:
            lines.append(f"GOAL REACHED in {step+1} steps.")
            break

    return "\n".join(lines)


# ──────────────────────────────────────────────
# Main
# ──────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="E₀ Canon Exposition Test")
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print the prompt without calling an LLM.",
    )
    parser.add_argument(
        "--self-graph", action="store_true",
        help="Enriched mode: include Self-Graph operational data.",
    )
    parser.add_argument(
        "--api-key", type=str, default=None,
        help="OpenAI API key (or set OPENAI_API_KEY env var).",
    )
    parser.add_argument(
        "--model", type=str, default="gpt-4o",
        help="Model to use for the exposition test.",
    )
    args = parser.parse_args()

    # Build context
    cl = load_canon("ontodynamics")

    if args.self_graph:
        # Enriched mode: run controller with self-graph attached
        sg = SelfGraph()
        ctrl = E0Controller(cl.landscape, lambda s, t: Outcome.SUCCESS)
        ctrl.self_graph = sg

        # Navigate to accumulate operational data
        current = "differenz"
        trace_lines = []
        for step in range(20):
            r = ctrl.cycle(current)
            if r is None:
                trace_lines.append(f"Step {step+1}: STUCK at {current}")
                break
            n_cands = len(r.candidates)
            trace_lines.append(
                f"Step {step+1}: {r.source} -> {r.target}"
                f"  (s_eff={r.s_eff:.4f}, candidates={n_cands})"
            )
            current = r.target
            if current == "negative_notwendigkeit":
                trace_lines.append(f"GOAL REACHED in {step+1} steps.")
                break
        trace = "\n".join(trace_lines)

        exposition = build_self_exposition(cl, sg)
        system = EXPOSITION_SYSTEM
        user = EXPOSITION_SELF_GRAPH_USER.format(exposition=exposition, trace=trace)
    else:
        # Basic mode: canon summary only
        summary = format_canon_summary(cl.info)
        trace = generate_trace()
        system = EXPOSITION_SYSTEM
        user = EXPOSITION_USER.format(summary=summary, trace=trace)

    if args.dry_run:
        print("=" * 72)
        print("SYSTEM PROMPT:")
        print("=" * 72)
        print(system)
        print()
        print("=" * 72)
        print("USER PROMPT:")
        print("=" * 72)
        print(user)
        print()
        print("=" * 72)
        print(f"Total length: {len(system) + len(user)} chars")
        print("=" * 72)
        return

    # Live LLM call
    from .llm_adapter import LLMConfig, openai_call

    config = LLMConfig(
        model=args.model,
        temperature=0.3,
        max_tokens=2048,
        api_key=args.api_key,
    )

    print("Sending exposition prompt to LLM...")
    print(f"  Model: {config.model}")
    print(f"  Mode: {'self-graph enriched' if args.self_graph else 'canon only'}")
    print(f"  Prompt length: {len(system) + len(user)} chars")
    print()

    response = openai_call(system, user, config)

    print("=" * 72)
    print("LLM REFLECTION:")
    print("=" * 72)
    print(response)
    print("=" * 72)


if __name__ == "__main__":
    main()
